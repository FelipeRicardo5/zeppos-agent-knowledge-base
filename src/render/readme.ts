import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { readDeviceFile, readExampleFiles, readModuleFiles, readPatternFiles } from "../store/read.js";
import type { Runtime, SymbolRecord } from "../types.js";

// The counts in the README, generated.
//
// This file exists because of a bug that has now shipped five times: a figure
// about the data, typed by hand into prose, that was true when it was written.
// The `29` that should have been `56`, the note claiming two runtimes were not
// extracted, "168 passing" when it was 170, "262 passing" when it was 335, and
// a coverage table that went stale twice in one afternoon. Each was corrected
// by hand, which is not a fix — it resets the clock.
//
// The rule the project already wrote for itself is "derive the figures that
// come from the data, or name the page to read instead of quoting it". This is
// the first half. The second half is prose: a sentence that quotes a number is
// rewritten to name the command or the page that prints it, and the numbers
// live only here.
//
// Written between markers rather than into a page of its own, because a README
// nobody can read end to end is worse than one with a generated block in it —
// and the reproducibility check in CI re-renders and fails on any diff, so a
// stale figure now breaks the build instead of misleading a reader.

const START = "<!-- coverage:start -->";
const END = "<!-- coverage:end -->";

/** Labels per README, so one computation serves both translations. */
